import fs from 'node:fs';
import Papa from 'papaparse';
const text = fs.readFileSync('scratch/item2-tdcc-offshore-yahoo-mapping.csv', 'utf8');
const parsed = Papa.parse(text, { header: true, skipEmptyLines: true });
const rows = parsed.data;
console.log('Total rows:', rows.length);
const found = rows.filter(r => r.yahoo_fund_id);
const exact = rows.filter(r => r.exact_match === 'true');
const notFound = rows.filter(r => !r.yahoo_fund_id);
const currencyBad = rows.filter(r => r.currency_consistent === 'false');
const classBad = rows.filter(r => r.class_consistent === 'false');
console.log(`found candidate: ${found.length}/${rows.length} (${(100*found.length/rows.length).toFixed(1)}%)`);
console.log(`exact name match: ${exact.length}/${rows.length} (${(100*exact.length/rows.length).toFixed(1)}%)`);
console.log(`not found: ${notFound.length}`);
console.log(`currency flagged inconsistent: ${currencyBad.length}`);
console.log(`class flagged inconsistent: ${classBad.length}`);
console.log('\nSample currency-inconsistent:');
for (const r of currencyBad.slice(0,5)) console.log(` DB: ${r.db_name} (${r.db_currency}) | Yahoo: ${r.yahoo_name}`);
console.log('\nSample not-found (first 10):');
for (const r of notFound.slice(0,10)) console.log(` ${r.db_code}: ${r.db_name}`);
